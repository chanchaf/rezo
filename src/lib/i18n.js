/**
 * Internationalisation (FR / EN / AR) — voir README "Langue et RTL" pour le contexte produit.
 *
 * Le français reste la langue de référence : toute clé manquante dans EN/AR retombe sur FR plutôt
 * que d'afficher la clé brute. Le contenu généré par les utilisateurs (titres de rencontre,
 * messages de chat, avis...) n'est JAMAIS traduit — seule l'interface l'est.
 *
 * L'arabe est RTL : voir `dir` ci-dessous, appliqué à la racine `.rezo-app` (attribut `dir`) qui
 * inverse nativement l'alignement du texte, la ponctuation et l'ordre des listes ; les overrides
 * CSS `[dir="rtl"]` du composant couvrent en plus la mise en page (nav, en-têtes, icônes
 * directionnelles) pour les zones où la direction est câblée en dur (flex row, position absolute).
 */

export const LANGUAGES = [
  { code: 'fr', flag: '🇫🇷', label: 'Français', dir: 'ltr' },
  { code: 'en', flag: '🇬🇧', label: 'English', dir: 'ltr' },
  { code: 'ar', flag: '🇲🇦', label: 'العربية', dir: 'rtl' },
];

export function dirForLanguage(code) {
  return (LANGUAGES.find((l) => l.code === code) || LANGUAGES[0]).dir;
}

// Langue du navigateur/appareil -> code supporté le plus proche, repli FR si aucune correspondance
// (jamais bloquant : l'utilisateur peut toujours changer via le sélecteur).
export function detectBrowserLanguage() {
  try {
    const nav = typeof navigator !== 'undefined' ? navigator.language || navigator.userLanguage : '';
    const primary = (nav || '').slice(0, 2).toLowerCase();
    if (LANGUAGES.some((l) => l.code === primary)) return primary;
    return 'fr';
  } catch (err) {
    return 'fr';
  }
}

