export const TRANSLATIONS = { fr, en, ar };

// Interpolation simple {var} -> valeur ; clé manquante dans la langue courante -> repli FR -> clé brute.
export function translate(lang, key, vars) {
  const dict = TRANSLATIONS[lang] || fr;
  let str = dict[key] ?? fr[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
    });
  }
  return str;
}
